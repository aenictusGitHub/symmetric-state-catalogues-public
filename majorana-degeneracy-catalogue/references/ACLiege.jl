# GHZ(x,y,z)
function pauliGHZxyz(k::Int64)::Array{Complex{Float64},2}
    if k==0
        paulik = paulix;
    elseif k==1
        paulik = pauliz;
    else
        throw(ArgumentError("Error OQLiege: undefined Pauli operator passed to paulik"))
        exit(code=1)
    end
end

function GHZ(x::Int64, y::Int64, z::Int64)::Vector{ComplexF64}
    GHZstate = (onec)*[1, 0, 0, 0, 0, 0, 0, 1]/sqrt(2)
    return (-1)^δkron(x,y,z)*kron(pauliGHZxyz(x),pauliGHZxyz(y),pauliGHZxyz(z))*GHZstate
end

function GHZ(N::Int64)::Vector{ComplexF64}
    return normalize(Dickeci(0,N)+Dickeci(N,N))
end

