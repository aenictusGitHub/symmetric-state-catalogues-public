# Optimal anticoherent state in the Dicke basis
function OACdk(N::Int64)::Array{Complex{Float64},1}
    if N<21
        dk = normalize!(convert(Vector{Complex{Float64}},filter(x -> x[1] == N, acstateslist)[1][2]))
	return dk
    else
        t = filter(x -> x[1] == N, acntlist)[1][2]
        #file = AC_dir*"acs."*string(N)*"."*string(t)*".txt" # Majorana unit vectors components
        file_redk = AC_dir*"acsredk."*string(N)*"."*string(t)*".txt"
        file_imdk = AC_dir*"acsimdk."*string(N)*"."*string(t)*".txt"
        if isfile(file_redk) && isfile(file_imdk)
            println("Reading OAC state file")
	    redk = readdlm(file_redk, '\n'; comments=true, comment_char='#')[:,1] # read vector
	    imdk = readdlm(file_imdk, '\n'; comments=true, comment_char='#')[:,1] # read vector
            #dk = readdlm(file, '\n', Complex{Float64}; comments=true, comment_char='#')
	    dk = convert(Vector{Complex{Float64}}, redk) .+ im * convert(Vector{Complex{Float64}}, imdk)
	    return dk
	else
            throw(ArgumentError("File $file_redk or $file_imdk passed to OACstate does not exist"))
        end
    end
end

