"""Build the portable KaTeX axis-label outline renderer from vendored fonts.

Run with a Python installation providing fontTools; no fonts are downloaded.
The output renders the same glyph outlines on Canvas and in native SVG paths.
"""
from pathlib import Path
import hashlib
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

ROOT = Path(__file__).resolve().parents[1]
CATALOGUES = ("symmetric-sector-catalogue", "anticoherent-state-catalogue",
              "ac-subspace-catalogue", "majorana-degeneracy-catalogue")
FONT_ROOT = ROOT / CATALOGUES[0] / "vendor/katex/fonts"
glyphs, sources = {}, {}
for filename, characters in (("KaTeX_Math-Italic.ttf", "Cxyz"),
                             ("KaTeX_Main-Regular.ttf", "0123456789∞")):
    source = FONT_ROOT / filename
    font = TTFont(source)
    assert font["head"].unitsPerEm == 1000
    cmap, glyph_set = font.getBestCmap(), font.getGlyphSet()
    sources[filename] = hashlib.sha256(source.read_bytes()).hexdigest()
    for character in characters:
        name = cmap[ord(character)]
        pen = SVGPathPen(glyph_set)
        glyph_set[name].draw(pen)
        shape = font["glyf"][name]
        glyphs[character] = {"path": pen.getCommands(),
                             "advance": font["hmtx"][name][0],
                             "bounds": [shape.xMin, shape.yMin, shape.xMax, shape.yMax]}
license_text = (ROOT / "scripts/majorana-latex-font-license.txt").read_text()
header = "/* Generated by scripts/build_majorana_latex.py.\n * C_n and x, y, z glyph outlines from the vendored KaTeX Math-Italic and Main fonts.\n * Glyph copyright: Design Science, Inc. 2009-2010; Khan Academy 2014-2018.\n * Font outlines are licensed under SIL OFL 1.1; see majorana-latex-LICENSE.txt.\n * No external fonts or raster images are required by these labels or exports.\n */\n"
source = r'''(function(global){
  'use strict';
  const glyphs=__GLYPHS__,fontSources=__SOURCES__;
  const metrics=Object.freeze({unitsPerEm:1000,baseAdvance:.715,scriptScale:.7,subscriptShift:.15,trailingSpace:.05});
  const number=x=>{if(!Number.isFinite(x))throw new Error('Finite LaTeX label coordinates are required.');return String(Number(x.toFixed(6)));};
  const escape=x=>String(x).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&apos;'}[c]));
  function orderKey(order){
    const text=String(order);
    if(/^[xyz]$/.test(text))return text;
    if(['continuous','infinity','∞','\\infty'].includes(text))return '∞';
    if(!/^\d{1,6}$/.test(text)||Number(text)<1)throw new Error('A positive integer, continuous symmetry order, or x, y, z coordinate label is required.');
    return String(Number(text));
  }
  function layout(order,size=16){
    if(!(Number.isFinite(size)&&size>0))throw new Error('A positive LaTeX label size is required.');
    const key=orderKey(order),coordinate=/^[xyz]$/.test(key),base=coordinate?key:'C',placements=[{key:base,x:0,y:0,scale:1}];let x=glyphs[base].advance;
    if(!coordinate)for(const character of key){placements.push({key:character,x,y:-150,scale:.7});x+=.7*glyphs[character].advance;}
    let bottom=Infinity,top=-Infinity;
    for(const p of placements){const b=glyphs[p.key].bounds;bottom=Math.min(bottom,p.y+p.scale*b[1]);top=Math.max(top,p.y+p.scale*b[3]);}
    const factor=size/1000;
    return {order:key,tex:coordinate?key:'C_{'+(key==='∞'?'\\infty':key)+'}',size,width:(x+(coordinate?0:50))*factor,height:(top-bottom)*factor,top:top*factor,bottom:bottom*factor,baselineOffset:(top+bottom)*factor/2,glyphs:placements};
  }
  const paths=new Map();
  function draw(context,order,x,y,size=16,color='#3f4241'){
    const box=layout(order,size);
    if(typeof context.mathAxisLabel==='function'){context.mathAxisLabel(order,x,y,size,color);return box;}
    context.save();context.translate(x-box.width/2,y+box.baselineOffset);context.scale(size/1000,-size/1000);
    for(const placement of box.glyphs){
      if(!paths.has(placement.key))paths.set(placement.key,new global.Path2D(glyphs[placement.key].path));
      context.save();context.translate(placement.x,placement.y);context.scale(placement.scale,placement.scale);
      context.lineJoin='round';context.lineWidth=3*1000/(size*placement.scale);context.strokeStyle='rgba(255,253,247,.82)';context.stroke(paths.get(placement.key));context.fillStyle=color;context.fill(paths.get(placement.key));context.restore();
    }
    context.restore();return box;
  }
  function toSVG(order,x,y,size=16,color='#3f4241'){
    const box=layout(order,size),left=x-box.width/2,baseline=y+box.baselineOffset;
    const shapes=box.glyphs.map(p=>`<path d="${glyphs[p.key].path}" transform="translate(${number(p.x)} ${number(p.y)}) scale(${number(p.scale)})" fill="${escape(color)}" stroke="#fffdf7" stroke-opacity=".82" stroke-width="${number(3*1000/(size*p.scale))}" stroke-linejoin="round" paint-order="stroke fill"/>`).join('');
    return `<g data-tex="${escape(box.tex)}" aria-label="${escape(box.tex)}" transform="translate(${number(left)} ${number(baseline)}) scale(${number(size/1000)} ${number(-size/1000)})">${shapes}</g>`;
  }
  const api=Object.freeze({draw,toSVG,layout,glyphs,fontSources,metrics});global.MajoranaLatex=api;
  if(typeof module==='object'&&module.exports)module.exports=api;
})(typeof window==='object'?window:globalThis);
'''
source = header + source.replace("__GLYPHS__", json.dumps(glyphs, ensure_ascii=False, separators=(",", ":"))).replace("__SOURCES__", json.dumps(sources, separators=(",", ":")))
for catalogue in CATALOGUES:
    target = ROOT / catalogue / "majorana-latex.js"
    target.write_text(source)
    target.with_name("majorana-latex-LICENSE.txt").write_text(license_text)
print(f"Generated {len(glyphs)} KaTeX outlines in {len(CATALOGUES)} renderer copies ({len(source.encode())} bytes each).")
