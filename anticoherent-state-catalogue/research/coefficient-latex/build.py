"""Generate display-only LaTeX for the catalogue's exact amplitude strings."""
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
import re
import sys

import sympy as sp


ROOT = Path(__file__).resolve().parents[2]
CATALOGUE = ROOT / "data/catalogue.json"
ASSET = ROOT / "data/coefficient-latex.js"


def validate_expression(expression: str) -> None:
    """Accept only the exact integer/radical arithmetic used by this dataset."""
    if not isinstance(expression, str):
        raise ValueError("An exact coefficient must be a string")
    if not re.fullmatch(r"(?:[0-9]+|sqrt|I|[-+*/()\s])+", expression):
        raise ValueError(f"Unsupported token in exact coefficient: {expression!r}")
    try:
        tree = ast.parse(expression, mode="eval")
    except SyntaxError as exc:
        raise ValueError(f"Invalid exact coefficient: {expression!r}") from exc

    def visit(node: ast.AST) -> None:
        if isinstance(node, ast.Expression):
            visit(node.body)
        elif isinstance(node, ast.Constant) and type(node.value) is int:
            return
        elif isinstance(node, ast.Name) and node.id == "I":
            return
        elif isinstance(node, ast.BinOp) and type(node.op) in (
            ast.Add, ast.Sub, ast.Mult, ast.Div
        ):
            visit(node.left)
            visit(node.right)
        elif isinstance(node, ast.UnaryOp) and type(node.op) in (ast.UAdd, ast.USub):
            visit(node.operand)
        elif (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id == "sqrt"
            and len(node.args) == 1
            and not node.keywords
        ):
            visit(node.args[0])
        else:
            raise ValueError(
                f"Unsupported syntax {type(node).__name__} in exact coefficient: "
                f"{expression!r}"
            )

    visit(tree)


def coefficient_latex(expression: str) -> str:
    validate_expression(expression)
    value = sp.sympify(expression, locals={"sqrt": sp.sqrt, "I": sp.I})
    if value.free_symbols:
        raise ValueError(f"Free symbols in exact coefficient: {expression!r}")
    if value.is_number is not True or value.is_finite is not True or value.has(sp.Float):
        raise ValueError(f"Coefficient is not a finite exact number: {expression!r}")
    # Use the standard printer directly: no simplify/refine/expand or decimal
    # evaluation. The original exact expression remains the mapping key.
    return sp.latex(value)


def build_asset(catalogue: dict) -> tuple[str, dict]:
    arrays = [state["exactCoefficients"] for state in catalogue["states"]
              if "exactCoefficients" in state]
    if not all(isinstance(array, list) for array in arrays):
        raise ValueError("Every exactCoefficients field must be an array")
    expressions = [expression for array in arrays for expression in array]
    if not all(isinstance(expression, str) for expression in expressions):
        raise ValueError("Every exact coefficient must be a string")
    unique = sorted(set(expressions))
    if "0" not in unique:
        raise ValueError("Expected the exact zero coefficient in the catalogue")
    mapping = {expression: coefficient_latex(expression) for expression in unique}
    body = json.dumps(mapping, ensure_ascii=False, indent=2)
    asset = (
        "/* Generated by research/coefficient-latex/build.py; display data only. */\n"
        "window.AC_COEFFICIENT_LATEX = Object.freeze(" + body + ");\n"
    )
    report = {
        "statesWithExactCoefficients": len(arrays),
        "exactCoefficientCount": len(expressions),
        "uniqueExpressions": len(mapping),
        "includesZero": "0" in mapping,
        "allExpressionsValidated": True,
        "allValuesFiniteExactAndSymbolFree": True,
        "assetBytes": len(asset.encode("utf-8")),
    }
    return asset, report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Verify that the checked-in display asset is current")
    args = parser.parse_args()
    asset, report = build_asset(json.loads(CATALOGUE.read_text(encoding="utf-8")))
    if args.check:
        if not ASSET.exists() or ASSET.read_text(encoding="utf-8") != asset:
            print("Exact-coefficient LaTeX asset is missing or out of date. "
                  "Run research/coefficient-latex/build.py to regenerate it.",
                  file=sys.stderr)
            return 1
        report["assetMatchesCatalogue"] = True
    else:
        ASSET.write_text(asset, encoding="utf-8")
        report["assetWritten"] = str(ASSET.relative_to(ROOT))
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
